export const LANGUAGES = ['en', 'ru', 'es', 'fr', 'de', 'it', 'pt'] as const

const TABLES = new Map<string, Strings>([
  ['en', en],
  ['ru', ru],
  ['es', es],
  ['fr', fr],
  ['de', de],
  ['it', it],
  ['pt', pt],
])

export function stringsFor(language: unknown, fallbackLocale = 'en'): Strings {
  const raw = typeof language === 'string' && language !== 'auto' ? language : fallbackLocale
  const code = raw.trim().toLowerCase().split(/[-_]/)[0] ?? 'en'
  return TABLES.get(code) ?? en
}
